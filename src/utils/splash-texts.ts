/**
 * Get a random splash text, avoiding recent duplicates
 */
const recentTexts: string[] = [];
export function getRandomSplashText(): string {
  // Get texts that haven't been shown recently
  const availableTexts = SPLASH_TEXTS.filter((text) => !recentTexts.includes(text));
  const pool = availableTexts.length > 0 ? availableTexts : SPLASH_TEXTS;

  const index = Math.floor(Math.random() * pool.length);
  const selected = pool[index] as string;

  // Track recent texts (keep last 10)
  recentTexts.push(selected);
  if (recentTexts.length > 10) {
    recentTexts.shift();
  }

  return selected;
}
